import { describe, expect, it } from 'vitest';
import { PrismaClient } from '@/generated/prisma/client';
import {
  CachedPrismaClient,
  isPrismaClientCurrent,
} from '@/infrastructure/persistence/prisma/prisma-client-guard';

const CURRENT_DELEGATES = [
  'doctor',
  'schedule',
  'dailyCount',
  'user',
  'session',
  'account',
  'verification',
  'patient',
  'consultation',
  'medicalExam',
  'therapySession',
  'specialtyRate',
];

function cache(
  delegates: string[],
  builtFrom: typeof PrismaClient = PrismaClient
): CachedPrismaClient {
  const client = Object.fromEntries(delegates.map((name) => [name, {}]));

  return { client: client as unknown as PrismaClient, builtFrom };
}

describe('isPrismaClientCurrent', () => {
  it('accepts a client built from the current constructor with every delegate', () => {
    expect(isPrismaClientCurrent(cache(CURRENT_DELEGATES))).toBe(true);
  });

  it('rejects the stale client that predates the SpecialtyRate model', () => {
    const stale = CURRENT_DELEGATES.filter((name) => name !== 'specialtyRate');

    expect(isPrismaClientCurrent(cache(stale))).toBe(false);
  });

  it('rejects a client missing only the newest model', () => {
    const missingMedicalExam = CURRENT_DELEGATES.filter((name) => name !== 'medicalExam');

    expect(isPrismaClientCurrent(cache(missingMedicalExam))).toBe(false);
  });

  it('rejects a complete client generated by an earlier build, which a schema change invalidates', () => {
    const previousBuild = class PreviousPrismaClient {} as unknown as typeof PrismaClient;

    expect(isPrismaClientCurrent(cache(CURRENT_DELEGATES, previousBuild))).toBe(false);
  });
});
